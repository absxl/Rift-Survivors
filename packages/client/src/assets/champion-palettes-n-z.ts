// Per-champion sprite palettes, N–Z (docs/10 D-048). Same format as A–M.
import type { ChampionSpriteStyle } from "./champion-palettes-a-m";

const P = (hex: string): number => Number.parseInt(hex, 16);

function ch(
  id: string,
  a: string,
  b: string,
  c: string,
  d: string,
  e?: string,
): [string, ChampionSpriteStyle] {
  if (e === undefined) {
    return [id, { hair: P(a), skin: P(b), cloth: P(c), accent: P(d) }];
  }
  return [id, { template: a as never, hair: P(b), skin: P(c), cloth: P(d), accent: P(e) }];
}

