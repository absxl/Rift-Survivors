/** Sprite for an enemy def id; falls back to the melee minion look. */
export function enemySprite(enemyId: string): Texture {
  const rows = ENEMY_SPRITES[enemyId] ?? ENEMY_SPRITES["melee-minion"];
  const paletteKey = enemyId.includes("dragon")
    ? "dragon"
    : enemyId.includes("baron")
      ? "baron"
      : enemyId.includes("herald")
        ? "herald"
        : enemyId.includes("colossal")
          ? "warden2"
          : enemyId.includes("warlord")
            ? "colossus"
            : enemyId.includes("blue")
              ? "blue"
              : enemyId.includes("red")
                ? "bramble"
                : enemyId.includes("krug")
                  ? "krug"
                  : enemyId.includes("gromp")
                    ? "gromp"
                    : enemyId.includes("wolf")
                      ? "wolf"
                      : enemyId.includes("raptor")
                        ? "raptor"
                        : enemyId.includes("scuttler")
                          ? "krug"
                          : enemyId.includes("caster")
                            ? "caster"
                            : enemyId.includes("cannon")
                              ? "cannon"
                              : enemyId.includes("super")
                                ? "super"
                                : enemyId.includes("hound")
                                  ? "hound"
                                  : enemyId.includes("warden")
                                    ? "warden"
                                    : "melee";
  return cachedRasterize(`enemy:${enemyId}`, rows, PALETTES[paletteKey]);
}
